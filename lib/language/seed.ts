// Só o inglês tem plano curado por enquanto. Idiomas sem seed abrem a mesma
// seção com as listas vazias — o usuário monta o próprio plano na mão ou pede
// pro assistente montar via MCP, exatamente como faz para complementar o inglês.
const PLANS: Partial<Record<LanguageCode, LanguagePlan>> = {
  en: { frames: EN_FRAMES, groups: EN_GROUPS, narrationPrompts: EN_NARRATION_PROMPTS },
};

export function planFor(language: LanguageCode | null): LanguagePlan {
  if (!language) return { frames: [], groups: [], narrationPrompts: [] };
  return PLANS[language] ?? { frames: [], groups: [], narrationPrompts: EN_NARRATION_PROMPTS };
}

export function hasCuratedPlan(language: LanguageCode | null): boolean {
  return !!language && !!PLANS[language];
}

export function countSeedWords(plan: LanguagePlan): number {
  return plan.groups.reduce((total, g) => total + g.words.length, 0);
}
